function generatePayments(): Payment[] {
  const result: Payment[] = []
  const now = new Date()
  for (let i = 5; i >= 0; i--) {
    const d = new Date(now.getFullYear(), now.getMonth() - i, 1)
    const month = `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}`
    const isCurrent = i === 0

    for (const s of mockStudents) {
      if (s.status === "Left" && s.checkOut && new Date(s.checkOut) < d) continue

      // Resolve the agreed price from the open room history entry (active on this date)
      const openHistory = mockRoomHistory.find(
        (h) =>
          h.studentId === s.id &&
          h.from <= `${month}-31` &&
          (!h.to || h.to >= `${month}-01`),
      )
      const room = mockRooms.find((r) => r.id === s.roomId)
      const totalFee =
        openHistory?.agreedMonthlyPrice ??
        s.monthlyFee ??
        room?.monthlyPrice ??
        12000

      let status: Payment["status"] = "Paid"
      let paidDate: string | undefined = `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-10`
      let amount = totalFee
      let paid = totalFee // default Paid

      // Sprinkle various states to demonstrate the UI
      if (s.id === "s7") {
        status = isCurrent ? "Outstanding" : "Paid"
        paid = status === "Outstanding" ? 0 : totalFee
        if (status === "Outstanding") paidDate = undefined
      } else if (s.id === "s4" && isCurrent) {
        status = "Pending"
        paid = 0
        paidDate = undefined
      } else if (s.id === "s1" && i === 1) {
        status = "Pending"
        paid = 0
        paidDate = undefined
      } else if (s.id === "s14" && (i === 0 || i === 1)) {
        status = "Partially Paid"
        amount = totalFee
        paid = 6000
        paidDate = `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-08`
      } else if (s.id === "s10" && isCurrent) {
        status = "Partially Paid"
        amount = totalFee
        paid = 8000
        paidDate = `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-05`
      } else if (s.id === "s13" && isCurrent) {
        status = "Pending"
        paid = 0
        paidDate = undefined
      } else if (s.id === "s17" && isCurrent) {
        status = "Outstanding"
        paid = 0
        paidDate = undefined
      }

      result.push({
        id: `p-${s.id}-${month}`,
        studentId: s.id,
        month,
        amount,
        paid,
        status,
        paidDate,
        type: "accommodation",
      })
    }
  }
  return result
}

